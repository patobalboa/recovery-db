-- NovaStore | Esquema académico (datos ficticios)
-- Ejecutar SOLO sobre una base de laboratorio nueva y vacía.
-- Este script no crea ni elimina bases de datos ni roles.
BEGIN;
CREATE SCHEMA IF NOT EXISTS novastore;
SET search_path TO novastore, public;

CREATE TABLE IF NOT EXISTS clientes (
  cliente_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  segmento TEXT NOT NULL CHECK (segmento IN ('PERSONA','PYME','EMPRESA')),
  region TEXT NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS productos (
  producto_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku TEXT NOT NULL UNIQUE,
  nombre TEXT NOT NULL,
  categoria TEXT NOT NULL,
  precio NUMERIC(12,2) NOT NULL CHECK (precio > 0),
  activo BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS pedidos (
  pedido_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id BIGINT NOT NULL REFERENCES clientes(cliente_id),
  fecha TIMESTAMPTZ NOT NULL,
  estado TEXT NOT NULL CHECK (estado IN ('PAGADO','PENDIENTE','CANCELADO')),
  canal TEXT NOT NULL CHECK (canal IN ('WEB','MOBILE','TIENDA')),
  total NUMERIC(14,2) NOT NULL CHECK (total >= 0),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS pedido_detalle (
  detalle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL REFERENCES pedidos(pedido_id),
  producto_id BIGINT NOT NULL REFERENCES productos(producto_id),
  cantidad INTEGER NOT NULL CHECK (cantidad > 0),
  precio_unitario NUMERIC(12,2) NOT NULL CHECK (precio_unitario > 0)
);

CREATE TABLE IF NOT EXISTS eventos_auditoria (
  evento_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entidad TEXT NOT NULL,
  entidad_id BIGINT NOT NULL,
  accion TEXT NOT NULL,
  ocurrido_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON SCHEMA novastore IS 'Dataset sintético para prácticas de recovery y optimización';
COMMIT;
